import { readFile, writeFile } from 'node:fs/promises'
import { dirname, isAbsolute, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { marked } from 'marked'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourceDirArgumentIndex = process.argv.indexOf('--source-dir')
const sourceDirArgument = sourceDirArgumentIndex >= 0 ? process.argv[sourceDirArgumentIndex + 1] : ''

if (!sourceDirArgument) {
  throw new Error('Missing --source-dir for the legal Markdown source files.')
}

const sourceDir = isAbsolute(sourceDirArgument)
  ? sourceDirArgument
  : resolve(projectRoot, sourceDirArgument)

const legalDocuments = [
  {
    sourceFileName: '万物有期_用户协议.md',
    outputFileName: 'userAgreementHtml.js',
    exportName: 'agreementHtml',
  },
  {
    sourceFileName: '万物有期_隐私政策.md',
    outputFileName: 'privacyPolicyHtml.js',
    exportName: 'privacyHtml',
  },
]

function formatDateMetadata(markdown) {
  return markdown.replace(
    /^\*\*(更新日期：[^^\r\n]+)\*\*\r?\n\*\*(生效日期：[^^\r\n]+)\*\*/m,
    '<div style="display:block;margin:0 0 36rpx;font-family:\'Noto Serif SC\',serif;font-size:27rpx;font-weight:700;line-height:52rpx;letter-spacing:1rpx;text-align:left;text-indent:0;color:#C47A5F;"><strong>$1</strong><br><strong>$2</strong></div>',
  )
}

for (const document of legalDocuments) {
  const sourcePath = resolve(sourceDir, document.sourceFileName)
  const outputPath = resolve(projectRoot, 'utils', document.outputFileName)
  const markdown = await readFile(sourcePath, 'utf8')
  const html = marked.parse(formatDateMetadata(markdown), {
    async: false,
    breaks: true,
    gfm: true,
  })
  const generatedModule = `// Generated by scripts/build-legal-pages.mjs. Do not edit manually.\nexport const ${document.exportName} = ${JSON.stringify(html)}\n`

  await writeFile(outputPath, generatedModule, 'utf8')
  console.log(`Generated ${outputPath}`)
}
