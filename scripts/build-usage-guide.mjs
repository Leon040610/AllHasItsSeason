import { readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, isAbsolute, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { marked } from 'marked'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const defaultSource = resolve(projectRoot, 'docs', 'usage-guide.md')
const outputPath = resolve(projectRoot, 'utils', 'usageGuideHtml.js')
const sourceArgumentIndex = process.argv.indexOf('--source')
const sourceArgument = sourceArgumentIndex >= 0 ? process.argv[sourceArgumentIndex + 1] : ''
const sourcePath = sourceArgument
  ? (isAbsolute(sourceArgument) ? sourceArgument : resolve(projectRoot, sourceArgument))
  : defaultSource

const guideImages = {
  'Pasted image 20260720194730.png': 'reminder-subscription.png',
  'Pasted image 20260720184643.png': 'guide-postscript-1.png',
  'Pasted image 20260720192426.png': 'guide-postscript-2.png',
}

if (!sourcePath) {
  throw new Error('Missing usage-guide Markdown source path.')
}

function preserveImageSlots(markdown) {
  let imageSlotIndex = 0
  const withImageSlots = markdown.replace(/!\[\[([^\]|]+)(?:\|[^\]]+)?\]\]/g, (_, imageName) => {
    imageSlotIndex += 1

    const imageFileName = guideImages[imageName]
    const imagePath = imageFileName && resolve(projectRoot, 'static', 'guide', imageFileName)
    if (imagePath && existsSync(imagePath)) {
      return `\n\n<img src="/static/guide/${imageFileName}" style="display:block;width:100%;height:auto;margin:28rpx 0;border-radius:24rpx;" data-guide-image-slot="${imageSlotIndex}" />\n\n`
    }

    return `\n\n<div style="height:260rpx;margin:28rpx 0;border:2rpx dashed #B8C2B4;border-radius:20rpx;background:#F4EFEA;" data-guide-image-slot="${imageSlotIndex}"></div>\n\n`
  })

  return withImageSlots
    .replace(/==\*{3}([\s\S]*?)\*{3}==/g, '\n\n<blockquote><strong><em>$1</em></strong></blockquote>\n\n')
    .replace(/==\*(.+?)\*==/g, '\n\n<blockquote><em>$1</em></blockquote>\n\n')
    .replace(/^==\*{3}(.+)$/gm, '\n\n<blockquote><strong><em>$1</em></strong></blockquote>\n\n')
    .replace(/~~([\s\S]+?)~~/g, '<del>$1</del>')
    .replace(/\n后期升级计划：/g, '\n\n后期升级计划：')
    .replace(/\n(小程序采取低成本开发|后期会把百度智能云替换| 如果后期累计独立访客| 我也不想接入广告)/g, '\n\n$1')
    .replace(/^- \[ \] /gm, '- □ ')
    .replace(/^- \[[xX]\] /gm, '- ☑ ')
}

const markdown = await readFile(sourcePath, 'utf8')
const guideHtml = marked.parse(preserveImageSlots(markdown), {
  async: false,
  breaks: true,
  gfm: true,
})

const generatedModule = `// Generated by scripts/build-usage-guide.mjs. Do not edit manually.\nexport const guideHtml = ${JSON.stringify(guideHtml)}\n`
await writeFile(outputPath, generatedModule, 'utf8')
console.log(`Generated ${outputPath}`)
